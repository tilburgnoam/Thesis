def tokenize(texts, entities, tokenizer):
    combined = texts + " [SEP] " + entities

    return tokenizer(
        combined.tolist(),
        padding=True,
        truncation=True,
        max_length=Config.max_length,
        return_tensors="pt"
    )

def create_datasets(train_enc, val_enc, test_enc, y_train, y_val, y_test):
    train_dataset = TensorDataset(
        train_enc["input_ids"],
        train_enc["attention_mask"],
        torch.tensor(y_train.values)
    )

    val_dataset = TensorDataset(
        val_enc["input_ids"],
        val_enc["attention_mask"],
        torch.tensor(y_val.values)
    )

    test_dataset = TensorDataset(
        test_enc["input_ids"],
        test_enc["attention_mask"],
        torch.tensor(y_test.values)
    )

    return train_dataset, val_dataset, test_dataset

def train_model(model, train_loader, optimizer, scheduler, loss_fn, device):
    model.train()
    total_loss = 0

    for input_ids, attention_mask, labels in train_loader:
        input_ids = input_ids.to(device)
        attention_mask = attention_mask.to(device)
        labels = labels.to(device)

        outputs = model(input_ids=input_ids, attention_mask=attention_mask)
        loss = loss_fn(outputs.logits, labels)

        loss.backward()
        optimizer.step()
        scheduler.step()
        optimizer.zero_grad()

        total_loss += loss.item()

    return total_loss / len(train_loader)

def evaluate(model, loader, device):
    model.eval()
    preds = []
    true = []

    with torch.no_grad():
        for input_ids, attention_mask, labels in loader:
            input_ids = input_ids.to(device)
            attention_mask = attention_mask.to(device)

            outputs = model(input_ids=input_ids, attention_mask=attention_mask)
            batch_preds = torch.argmax(outputs.logits, dim=-1)

            preds.extend(batch_preds.cpu().numpy())
            true.extend(labels.numpy())

    return true, preds

def run_experiment(df, seed, tokenizer, device, le):

    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    torch.cuda.manual_seed_all(seed)
    os.environ["PYTHONHASHSEED"] = str(seed)
    torch.backends.cudnn.deterministic = True
    torch.backends.cudnn.benchmark = False

    # Data
    X_train, X_train_entity, y_train, \
    X_val, X_val_entity, y_val, \
    X_test, X_test_entity, y_test = prepare_data(df, seed)

    # Tokenization
    train_enc = tokenize(X_train, X_train_entity, tokenizer)
    val_enc   = tokenize(X_val, X_val_entity, tokenizer)
    test_enc  = tokenize(X_test, X_test_entity, tokenizer)

    # Dataset
    train_dataset, val_dataset, test_dataset = create_datasets(
        train_enc, val_enc, test_enc, y_train, y_val, y_test
    )

    g = torch.Generator()
    g.manual_seed(seed)
    train_loader = DataLoader(train_dataset, batch_size=Config.batch_size, shuffle=True, generator=g)
    val_loader   = DataLoader(val_dataset, batch_size=Config.batch_size)
    test_loader  = DataLoader(test_dataset, batch_size=Config.batch_size)

    model = AutoModelForSequenceClassification.from_pretrained(
    Config.checkpoint, num_labels=5).to(device)

    optimizer = torch.optim.AdamW(model.parameters(), lr=Config.lr)

    loss_fn = torch.nn.CrossEntropyLoss()

    num_epochs = Config.epochs
    num_training_steps = num_epochs * len(train_loader)

    scheduler = get_scheduler(
        "linear",
        optimizer=optimizer,
        num_warmup_steps=0,
        num_training_steps=num_training_steps
    )

    # Train
    for epoch in range(num_epochs):
        loss = train_model(model, train_loader, optimizer, scheduler, loss_fn, device)
        print(f"Epoch {epoch+1} Loss: {loss:.4f}")

    # Evaluate
    y_true, y_pred = evaluate(model, test_loader, device)


    print("\n===== Classification Report =====")
    print(classification_report(y_true, y_pred, target_names=le.classes_, zero_division=0))


    macro = f1_score(y_true, y_pred, average='macro')
    weighted = f1_score(y_true, y_pred, average='weighted')
    acc = accuracy_score(y_true, y_pred)

    return macro, weighted, acc, model

